export function getBrandPageCopy(slug: string, brandName: string): BrandPageCopy {
  const entry = COPY[slug];
  if (entry) {
    return entry;
  }

  return {
    headlineName: brandName.toUpperCase(),
    paragraphs: [
      `Каталог кварцевого агломерата ${brandName} с актуальными декорами, цветами и ориентировочными ценами для столешниц, подоконников и других изделий.`
    ]
  };
}

export function brandPageDescriptionSummary(slug: string, brandName: string) {
  const { paragraphs } = getBrandPageCopy(slug, brandName);
  return paragraphs[0];
}
