/** Находит описание модели по названию из базы («МК1 стандарт» → модель 1). Латинские MK тоже считаем. */
export function sinkSpecFor(name: string): SinkModelSpec | undefined {
  const match = /[МM][КK]\s*([1-4])/i.exec(name);
  return match ? sinkModelSpecs.find((spec) => spec.key === match[1]) : undefined;
}

